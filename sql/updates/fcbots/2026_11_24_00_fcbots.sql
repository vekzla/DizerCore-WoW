-- FCBots: name pool for bot characters. The server picks an unused name when it creates a bot
-- character and marks it used. characters.characters has a unique index on name, so a clash
-- with a player character fails at insert time and the server picks another name.

CREATE TABLE `bot_names` (
  `name` varchar(12) CHARACTER SET utf8mb4 COLLATE utf8mb4_bin NOT NULL COMMENT 'character name, unique',
  `used` tinyint unsigned NOT NULL DEFAULT 0 COMMENT '0 free, 1 assigned to a bot character',
  `assigned_at` timestamp NULL DEFAULT NULL,
  PRIMARY KEY (`name`),
  KEY `idx_used` (`used`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci COMMENT='FCBots random character name pool';

